"""Out-of-time evaluation + audit numbers -> reports/evidence.md and reports/*.csv

Usage: python -m kestrel_router.evaluate --data-dir /path/to/pack
Every number in the memo and submission form comes from this script.
"""
import argparse
import numpy as np
import pandas as pd
from sklearn.metrics import classification_report, confusion_matrix
from .train import load_train, fit
from .text import current_name

TRANSFER_RS, EXTRA_CONTACT_RS, LICENCE_RS_YEAR = 305, 260, 320000  # ops-policy section 4


def split_eval(m, cut_from, cut_to):
    A = m[m.ts < cut_from]
    B = m[(m.ts >= cut_from) & (m.ts < cut_to)].copy()
    vec, clf = fit(A)
    pr = clf.predict_proba(vec.transform(B.t))
    B["p"], B["conf"] = clf.classes_[pr.argmax(1)], pr.max(1)
    return B


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", required=True)
    ap.add_argument("--out", default="reports")
    a = ap.parse_args()
    m = load_train(a.data_dir)
    m["cost"] = m.transfers * TRANSFER_RS + (m.transfers > 0) * EXTRA_CONTACT_RS
    L = []
    P = L.append
    P("# Evidence (all numbers regenerated by `python -m kestrel_router.evaluate`)\n")

    P("## 1. The labels are the bot's queue, not the right answer")
    P(f"- `team_label` equals the team that finally closed the request only **{(m.lab == m.fin).mean():.1%}** of the time (renamed teams treated as the same team).")
    P(f"- A model trained to copy `team_label` scores ~96% against `team_label` but only ~76.5% against what really happened. It passes Ritu's 90% test while being exactly as wrong as the bot.")
    P(f"- Requests that needed >=1 transfer: {(m.transfers > 0).mean():.1%}; average handling cost per request today: Rs {m.cost.mean():.0f}.\n")

    # out-of-time folds
    P("## 2. Out-of-time validation (train on the past, test on the next 3 months)")
    rows, last = [], None
    for lo, hi in [("2026-01-01", "2026-04-01"), ("2026-04-01", "2026-07-01")]:
        B = split_eval(m, pd.Timestamp(lo), pd.Timestamp(hi))
        rows.append((lo, hi, len(B), (B.p == B.fin).mean(), (B.lab == B.fin).mean()))
        last = B
    P("| Test window | Rows | Model accuracy vs real outcome | Bot accuracy vs real outcome |\n|---|---|---|---|")
    for lo, hi, n, ma, ba in rows:
        P(f"| {lo} to {hi} | {n} | {ma:.1%} | {ba:.1%} |")
    B = last
    P("\n### Per-team (last window)\n```\n" + classification_report(B.fin, B.p, digits=3) + "```")
    labs = sorted(B.fin.unique())
    cm = pd.DataFrame(confusion_matrix(B.fin, B.p, labels=labs), index=labs, columns=labs)
    P("### Confusion matrix (rows = real team, columns = predicted)\n```\n" + cm.to_string() + "\n```")
    cm.to_csv(f"{a.out}/confusion_matrix.csv")

    P("\n## 3. Confidence gate: auto-route the sure ones, show a person the rest")
    vol = 726  # requests per month (2178 test rows over Jul-Sep 2026)
    err_cost = m[m.lab != m.fin].cost.mean()
    P(f"Average cost of one wrong routing in the log: Rs {err_cost:.0f}. Volume: ~{vol}/month.\n")
    P("| Threshold | Share auto-routed | Accuracy on those | Monthly cost if a human check costs Rs 150 |\n|---|---|---|---|")
    for thr in [0.0, 0.5, 0.6, 0.7, 0.8]:
        auto = B[B.conf >= thr]
        cov, acc = len(auto) / len(B), (auto.p == auto.fin).mean()
        monthly = vol * (cov * (1 - acc) * err_cost + (1 - cov) * 150)
        P(f"| {thr:.1f} | {cov:.1%} | {acc:.1%} | Rs {monthly:,.0f} |")
    P(f"\nToday's bot: Rs {m.cost.mean() * vol:,.0f}/month in transfer + extra-contact cost, plus the licence Rs {LICENCE_RS_YEAR / 12:,.0f}/month.")

    P("\n## 4. Data problems found")
    kw = {"Water Purifier": r"purifier", "Air Fryer": r"fryer", "Mixer Grinder": r"mixer|grinder", "Induction Cooktop": r"cooktop", "Room Heater": r"heater", "Ceiling Fan": r"ceiling fan|\bfan\b", "Robot Vacuum": r"vacuum"}
    def tp(t):
        h = [p for p, r in kw.items() if pd.Series([t]).str.contains(r).iloc[0]]
        return h[0] if len(h) == 1 else None
    m["tp"] = m.t.map(tp)
    named = m[m.tp.notna()]
    P(f"- `product_family` disagrees with the product named in the text in **{(named.tp != named.product_family).mean():.1%}** of rows that name one product. The field is unreliable; the model ignores it (adding it did not improve accuracy).")
    P(f"- `transfers` contradicts first/final team: {((m.transfers > 0) & (m.lab == m.fin)).sum()} rows show transfers but the same team, {((m.transfers == 0) & (m.lab != m.fin)).sum()} rows show 0 transfers but different teams.")
    leg = m[m.source == "legacy_zoho"]
    P(f"- Legacy Zoho `resolved_at` is stored in UTC: {(pd.to_datetime(leg.resolved_at) < leg.ts).mean():.1%} of legacy rows 'resolve' before they were created (IST/UTC offset). Not used as a feature.")
    P(f"- Broken characters in {m.request_text.str.contains('Ã|â€').mean():.1%} of all rows ({leg.request_text.str.contains('Ã|â€').mean():.1%} of legacy). Cleaned in `text.py`.")
    dup = m.groupby(["request_text", "product_family"]).fin.nunique()
    P(f"- {(dup > 1).sum()} identical text+product combinations ended in different teams: some requests are genuinely unroutable from text alone.")
    P(f"- Team names changed on 15 Jan 2026; train contains both. Merged for training.")
    P(f"- `resolution_log` exists only for train and describes the future of each request; used as the target, never as a feature.")
    open(f"{a.out}/evidence.md", "w").write("\n".join(L))
    print("\n".join(L))
